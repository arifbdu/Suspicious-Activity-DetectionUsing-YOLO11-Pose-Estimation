# ============================================================
# main.py
#
# Real-time suspicious-activity detection using:
#   - YOLOv11-Pose for keypoint extraction
#   - Final standard-KNN pipeline saved as best_model.pkl
#
# Class mapping:
#   0 = Normal
#   1 = Suspicious
# ============================================================

from pathlib import Path
import json

import cv2
import cvzone
import joblib
import numpy as np
import pandas as pd
from ultralytics import YOLO


# ============================================================
# File paths
# ============================================================

BASE_DIR = Path(__file__).resolve().parent

VIDEO_PATH = BASE_DIR / "VID_c.mp4"

YOLO_MODEL_PATH = BASE_DIR / "yolo11n-pose.pt"

KNN_MODEL_PATH = BASE_DIR / "best_model.pkl"

METADATA_PATH = (
    BASE_DIR
    / "reviewer1_outputs"
    / "best_knn_model_metadata.json"
)


# ============================================================
# General settings
# ============================================================

CONFIDENCE_THRESHOLD = 0.55

FRAME_SKIP_INTERVAL = 2

DISPLAY_WIDTH = 1018

DISPLAY_HEIGHT = 600


# ============================================================
# Load model and metadata
# ============================================================

def load_knn_model():
    """
    Load the final KNN pipeline generated by model.py.

    The saved pipeline already performs:
      1. Median imputation
      2. Mutual-information-based feature selection
      3. Standard scaling
      4. Standard-KNN prediction
    """

    if not KNN_MODEL_PATH.exists():
        raise FileNotFoundError(
            f"\nKNN model not found:\n{KNN_MODEL_PATH}\n\n"
            "Run model.py first to generate best_model.pkl."
        )

    return joblib.load(KNN_MODEL_PATH)


def load_feature_columns():
    """
    Load the original feature-column order used during training.

    The KNN pipeline expects all original 34 input features.
    Feature selection is applied internally by the pipeline.
    """

    if METADATA_PATH.exists():
        with open(
            METADATA_PATH,
            "r",
            encoding="utf-8",
        ) as file:
            metadata = json.load(file)

        columns = metadata.get(
            "Original_Feature_Columns_In_Required_Order"
        )

        if columns:
            return columns

    # Fallback order:
    # x0, y0, x1, y1, ..., x16, y16
    return [
        feature_name
        for index in range(17)
        for feature_name in (
            f"x{index}",
            f"y{index}",
        )
    ]


# ============================================================
# Keypoint preparation
# ============================================================

def create_feature_dataframe(
    person_keypoints,
    feature_columns,
):
    """
    Convert one detected person's pose keypoints into the
    DataFrame format expected by the trained KNN pipeline.

    person_keypoints:
        List containing 17 normalized [x, y] keypoint pairs.
    """

    feature_values = {}

    for index in range(17):
        if index < len(person_keypoints):
            x_value = person_keypoints[index][0]
            y_value = person_keypoints[index][1]
        else:
            # Missing values will be handled by the imputer
            # saved inside the KNN pipeline.
            x_value = np.nan
            y_value = np.nan

        feature_values[f"x{index}"] = x_value
        feature_values[f"y{index}"] = y_value

    dataframe = pd.DataFrame(
        [feature_values]
    )

    # Match the exact feature order used during training.
    dataframe = dataframe.reindex(
        columns=feature_columns
    )

    return dataframe


# ============================================================
# Video detection
# ============================================================

def detect_suspicious_activity(
    video_path,
):
    """
    Process a video and classify each detected person's pose
    as Normal or Suspicious.
    """

    if not Path(video_path).exists():
        raise FileNotFoundError(
            f"Video file not found: {video_path}"
        )

    if not YOLO_MODEL_PATH.exists():
        raise FileNotFoundError(
            f"YOLO pose model not found: {YOLO_MODEL_PATH}"
        )

    # Load YOLOv11-Pose.
    pose_model = YOLO(
        str(YOLO_MODEL_PATH)
    )

    # Load the final standard-KNN pipeline.
    knn_model = load_knn_model()

    # Load the original 34-column feature order.
    feature_columns = load_feature_columns()

    print("=" * 70)
    print("Suspicious-activity detection started")
    print("=" * 70)
    print(f"Video: {video_path}")
    print(f"YOLO model: {YOLO_MODEL_PATH.name}")
    print(f"Classifier: {KNN_MODEL_PATH.name}")
    print("Class mapping: 0 = Normal, 1 = Suspicious")
    print("=" * 70)

    cap = cv2.VideoCapture(
        str(video_path)
    )

    if not cap.isOpened():
        print("Error: Could not open the video file.")
        return

    total_frames = int(
        cap.get(
            cv2.CAP_PROP_FRAME_COUNT
        )
    )

    print(f"Total frames: {total_frames}")

    frame_number = 0

    while cap.isOpened():
        success, frame = cap.read()

        if not success:
            print("Video processing completed.")
            break

        frame_number += 1

        # Process every second frame to reduce computation.
        if (
            frame_number
            % FRAME_SKIP_INTERVAL
            != 0
        ):
            continue

        frame = cv2.resize(
            frame,
            (
                DISPLAY_WIDTH,
                DISPLAY_HEIGHT,
            ),
        )

        results = pose_model(
            frame,
            verbose=False,
        )

        annotated_frame = results[0].plot(
            boxes=False
        )

        for result in results:
            if (
                result.boxes is None
                or result.keypoints is None
            ):
                continue

            bounding_boxes = (
                result.boxes.xyxy
                .cpu()
                .tolist()
            )

            confidence_scores = (
                result.boxes.conf
                .cpu()
                .tolist()
            )

            normalized_keypoints = (
                result.keypoints.xyn
                .cpu()
                .tolist()
            )

            print(
                f"Frame {frame_number}: "
                f"detected {len(bounding_boxes)} person(s)"
            )

            for index, box in enumerate(
                bounding_boxes
            ):
                if (
                    confidence_scores[index]
                    <= CONFIDENCE_THRESHOLD
                ):
                    continue

                if index >= len(
                    normalized_keypoints
                ):
                    continue

                x1, y1, x2, y2 = box

                feature_dataframe = (
                    create_feature_dataframe(
                        person_keypoints=(
                            normalized_keypoints[
                                index
                            ]
                        ),
                        feature_columns=(
                            feature_columns
                        ),
                    )
                )

                # The saved pipeline automatically performs
                # preprocessing and feature selection.
                prediction = int(
                    knn_model.predict(
                        feature_dataframe
                    )[0]
                )

                print(
                    f"Frame {frame_number}, "
                    f"person {index + 1}: "
                    f"prediction = {prediction}"
                )

                # Revised mapping:
                # 0 = Normal
                # 1 = Suspicious
                if prediction == 1:
                    label = "Suspicious"
                    box_color = (
                        0,
                        0,
                        255,
                    )

                else:
                    label = "Normal"
                    box_color = (
                        0,
                        255,
                        0,
                    )

                cv2.rectangle(
                    annotated_frame,
                    (
                        int(x1),
                        int(y1),
                    ),
                    (
                        int(x2),
                        int(y2),
                    ),
                    box_color,
                    2,
                )

                cvzone.putTextRect(
                    annotated_frame,
                    label,
                    (
                        int(x1),
                        max(
                            int(y1) - 10,
                            30,
                        ),
                    ),
                    scale=1,
                    thickness=1,
                    colorR=box_color,
                )

        cv2.imshow(
            "Online Proctoring - Suspicious Activity Detection",
            annotated_frame,
        )

        # Press q to stop processing.
        if (
            cv2.waitKey(1)
            & 0xFF
            == ord("q")
        ):
            print("Processing stopped by user.")
            break

    cap.release()

    cv2.destroyAllWindows()


# ============================================================
# Run
# ============================================================

if __name__ == "__main__":
    detect_suspicious_activity(
        VIDEO_PATH
    )